# Buat program untuk menghitung luas persegi panjang
# Nama variabel ditambah 4 digit nim terakhir contoh: panjang_1234
# Program ini menggunakan fungsi input() untuk meminta pengguna
# memasukkan nilai panjang dan lebar persegi panjang.
# Nilai yang dimasukkan akan dikonversi menjadi tipe data integer
panjang_2018 = input('Masukan nilai panjang: ')
lebar_2018 = input('Masukkan nilai lebar: ')
luas_2018 = int(panjang_2018) * int(lebar_2018)
print("Luas:", luas_2018)